class Expense
{
    // Attributes
    public string? name;
    public double amount = 0;
    public string? category;

    // Constructors
    public Expense() { }
    public Expense(string? name, double amount, string? category)
    {
        this.name = name;
        this.amount = amount;
        this.category = category;
    }

    // Methods



}